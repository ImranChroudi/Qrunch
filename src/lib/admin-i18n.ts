function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    vars[key] !== undefined ? String(vars[key]) : `{${key}}`,
  );
}

export function adminStrings(locale: AdminLocale): Dictionary {
  return STRINGS[locale] ?? STRINGS.en;
}

export function adminT(locale: AdminLocale, key: string, vars?: Record<string, string | number>): string {
  const dict = adminStrings(locale);
  const template = dict[key] ?? STRINGS.en[key] ?? key;
  return interpolate(template, vars);
}

