export type AdminLocale = "en" | "fr" | "ar";

export const ADMIN_LOCALES: { code: AdminLocale; label: string; dir: "ltr" | "rtl" }[] = [
  { code: "en", label: "English", dir: "ltr" },
  { code: "fr", label: "Français", dir: "ltr" },
  { code: "ar", label: "العربية", dir: "rtl" },
];

export const ADMIN_LANGUAGE_STORAGE_KEY = "menuqr:admin-language";
export const ADMIN_LANGUAGE_COOKIE_KEY = "menuqr_admin_lang";

export function isAdminLocale(value: string | null | undefined): value is AdminLocale {
  return value === "en" || value === "fr" || value === "ar";
}

export function normaliseAdminLocale(value: string | null | undefined): AdminLocale {
  return isAdminLocale(value) ? value : "en";
}

export function dirForAdmin(locale: AdminLocale): "ltr" | "rtl" {
  return ADMIN_LOCALES.find((entry) => entry.code === locale)?.dir ?? "ltr";
}

export function localeTagAdmin(locale: AdminLocale): string {
  return locale;
}

